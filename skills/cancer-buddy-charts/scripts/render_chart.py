"""Clinical chart recipes for cancer-buddy (stdlib only, ZERO medical logic).

Layer 2 of the two-layer design — see chart_core.py for layer 1 (primitives).
Each recipe below composes primitives; it does not own an engine. A chart type
nobody anticipated is a NEW RECIPE built from the same primitives, which is what
lets this skill answer a request outside the catalogue instead of failing over
to "not supported" (references/chart-catalog.md §3, SKILL.md §generalisation).

CHANNEL A — 段D case-summary embed (backwards compatible)
    Drop-in replacement for compute_sparklines.py. Same CLI, same emitted
    fields, same exit codes, byte-identical geometry for trend_charts[] and
    lab_trends[]. New capability is additive (reference_band, reading_note),
    never a change to an existing field.

        python3 render_chart.py --data case_summary_data.json \
            [--out enriched.json] [--longitudinal L.json] [--labs labs.json]

CHANNEL B — standalone chart file (paths B and C)
    Assembles a complete self-contained HTML file. No template renderer, no JS,
    no external font, no CDN.

        python3 render_chart.py --chart trend --from-longitudinal L.json \
            --metric CEA --out-html cea.html
        python3 render_chart.py --chart <recipe> --spec spec.json --out-html f.html

Exit codes:
    0  — ok
    2  — bad invocation / unreadable / malformed input
    3  — anti-fabrication gate failed (a plotted value is absent from the source)
    4  — caption/title gate failed (a verdict-bearing phrase reached the output)
    5  — eligibility gate failed (series not eligible to be graphed)
"""
