def run_channel_b(args) -> int:
    if args.from_labs:
        if not args.metric:
            print("ERROR: --from-labs requires --metric", file=sys.stderr)
            return 2
        try:
            spec = spec_from_labs(args.from_labs, args.metric)
        except Eligibility as e:
            print(f"NOT ELIGIBLE: {e}", file=sys.stderr)
            return 5
        except Exception as e:
            print(f"ERROR: cannot read --from-labs: {e}", file=sys.stderr)
            return 2
    elif args.from_longitudinal:
        if not args.metric:
            print("ERROR: --from-longitudinal requires --metric", file=sys.stderr)
            return 2
        try:
            spec = spec_from_longitudinal(args.from_longitudinal, args.metric)
        except Eligibility as e:
            print(f"NOT ELIGIBLE: {e}", file=sys.stderr)
            return 5
        except Exception as e:
            print(f"ERROR: cannot read --from-longitudinal: {e}", file=sys.stderr)
            return 2
    else:
        try:
            spec = json.loads(Path(args.spec).read_text(encoding="utf-8"))
        except Exception as e:
            print(f"ERROR: cannot read/parse --spec: {e}", file=sys.stderr)
            return 2

    recipe = RECIPES.get(args.chart)
    if recipe is None:
        print(f"ERROR: unknown --chart {args.chart!r}. known: {', '.join(sorted(RECIPES))}. "
              f"A chart outside this list is a NEW RECIPE composed from chart_core "
              f"primitives — see SKILL.md §generalisation.", file=sys.stderr)
        return 2
    try:
        svg, note, legend, caveats, subject = recipe(spec)
    except Eligibility as e:
        print(f"NOT ELIGIBLE: {e}", file=sys.stderr)
        return 5

    title = args.title or f"{subject} · 源报告记录"
    # G-CHART-1 floor, AUTHORED text only (see the scope note at the gate).
    # `note`/`caveats`/`legend` are produced by the deterministic recipes above
    # and are governed by code review, not by this runtime regex.
    viol = verdict_violations(args.title, spec.get("title"), spec.get("caption"))
    if viol:
        for text, phrase in viol:
            print(f"ERROR: verdict gate — {phrase!r} in {text!r}", file=sys.stderr)
        return 4

    src = args.source or "数据来源：本人上传的检验/病历报告，数值逐条转录，未做换算或推断。"
    html = page(title, note, svg.markup(), legend, src, caveats)
    out = Path(args.out_html)
    out.write_text(html, encoding="utf-8")
    print(f"chart → {out} ({len(html)} bytes, recipe={args.chart})")
    return 0


def run_channel_a(args) -> int:
    try:
        data = json.loads(Path(args.data).read_text(encoding="utf-8"))
    except Exception as e:
        print(f"ERROR: cannot read/parse --data: {e}", file=sys.stderr)
        return 2
    if not isinstance(data, dict):
        print("ERROR: --data root must be a JSON object", file=sys.stderr)
        return 2

    if args.longitudinal or args.labs:
        idx = _source_index([args.longitudinal, args.labs])
        violations = _integrity_violations(data, idx)
        if violations:
            print("ERROR: anti-fabrication gate — plotted value(s) absent from source store:",
                  file=sys.stderr)
            for v in violations:
                print(f"  - {v}", file=sys.stderr)
            return 3

    # G-CHART-1 floor over every caption-bearing field
    texts = []
    for c in (data.get("trend_charts") or []):
        if isinstance(c, dict):
            texts += [c.get("reading_note"), c.get("interpretation"), c.get("title")]
    viol = verdict_violations(*texts)
    if viol:
        for text, phrase in viol:
            print(f"ERROR: verdict gate — {phrase!r} in {text!r}", file=sys.stderr)
        return 4

    enrich(data)

    out = args.out or args.data
    Path(out).write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    n_charts = sum(1 for c in (data.get("trend_charts") or []) if isinstance(c, dict))
    n_labs = sum(1 for r in (data.get("lab_trends") or []) if isinstance(r, dict))
    print(f"enriched → {out} (trend charts={n_charts}, lab_trend rows={n_labs})")
    return 0


