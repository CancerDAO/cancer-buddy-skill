# ── C9 · two-timepoint dumbbell ──────────────────────────────────────────────
def recipe_dumbbell(spec):
    rows = [r for r in (spec.get("rows") or []) if isinstance(r, dict)]
    rows = [r for r in rows
            if to_float(r.get("v1")) is not None and to_float(r.get("v2")) is not None]
    if not rows:
        raise Eligibility("没有同时具备两个时点数值的项目。")
    lane, top, lx = 21.0, 34.0, 116.0
    h = top + lane * len(rows) + 16.0
    svg = Svg(FIG_W, h, label="两个时点的数值对照")
    x2 = FIG_W - 84.0
    # PER-ROW normalisation. A shared value axis across rows would put 68 kg and
    # 132 g/L on one scale, making bar length a comparison between quantities
    # that have no common dimension — the chart would read as "haemoglobin moved
    # more than weight", which is meaningless. Each row is scaled to its OWN two
    # values, so length encodes only that row's movement, and the legend says so.
    svg.text(lx, top - 14, esc(spec.get("t1_label", "时点 1")), size=FS_AXIS, fill=MUTED)
    svg.text(x2, top - 14, esc(spec.get("t2_label", "时点 2")), size=FS_AXIS,
             fill=MUTED, anchor="end")
    for i, r in enumerate(rows):
        y = top + i * lane
        shown, full = truncate(r.get("label", ""), 15)
        svg.text(6, y + 3, shown, size=FS_BODY, fill=INK, weight=600,
                 title=full if full != shown else None)
        a, b = to_float(r["v1"]), to_float(r["v2"])
        # Position encodes the value as a FRACTION OF THAT ROW'S OWN maximum, so
        # x means something (how far this reading sits below its own peak) and
        # the segment length means something (how much it moved, proportionally).
        # It must NOT be ordered by magnitude: doing that put "68.0 → 61.5" on
        # screen as 61.5 on the left, silently reversing time. Which end is
        # earlier is carried by the marker (hollow = first), never by position.
        rmax = max(abs(a), abs(b)) or 1.0
        def rx(v):
            return lx + (x2 - lx) * (0.08 + 0.86 * (v / rmax))
        xa, xb = rx(a), rx(b)
        svg.line(lx, y, x2, y, stroke=RULE, width=0.5)
