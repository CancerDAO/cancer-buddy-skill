def _pts_from_spec(series):
    """Normalise a spec series into ordered point dicts."""
    out = []
    for p in series or []:
        if not isinstance(p, dict):
            continue
        o = to_ordinal(p.get("t"))
        v = to_float(p.get("v"))
        out.append({
            "o": o, "v": v, "raw": p.get("v"), "t": p.get("t"),
            "unit": p.get("unit"), "method": p.get("method"),
            "ref": p.get("reference_range"), "critical": bool(p.get("critical")),
            "censor": censoring(p.get("v")),
        })
    out.sort(key=lambda p: (p["o"] is None, p["o"] or 0))
    return out


def _date_label(t) -> str:
    s = str(t or "")
    return s[:7] if len(s) >= 7 else s


# ── C1 · trend with reference band ───────────────────────────────────────────
def recipe_trend(spec):
    metric = spec.get("metric", "")
    unit = spec.get("unit", "")
    pts = [p for p in _pts_from_spec(spec.get("series")) if p["v"] is not None and p["o"] is not None]
    if len(pts) < 2:
        raise Eligibility("序列不足 2 个可比数据点，无法绘制趋势图。")
    ref = parse_reference_range(spec.get("reference_range")
                                or next((p["ref"] for p in pts if p["ref"]), None))
    h = 150.0
    tax = TimeAxis([p["o"] for p in pts], FIG_W, FIG_PAD)
    vax = ValueAxis([p["v"] for p in pts], h, 22.0, ref=ref)
    svg = Svg(FIG_W, h, label=f"{metric} 随时间的测量值")
    dropped, gaps_drawn = [], []

    # furniture first — the band and rails live under the data
    band_squashed = False
    if ref:
        lo, hi = ref
        y_lo = vax.y(lo) if lo is not None else h - 22.0
        y_hi = vax.y(hi) if hi is not None else 22.0
        # A value far above the range (CA19-9 412 against 0–37) squashes the band
        # to a hairline. Enforce a visible minimum so it stays legible, and SAY
        # in the reading note that it is no longer to scale — a band you cannot
        # see and a band you happen to sit inside look identical otherwise.
        if abs(y_lo - y_hi) < 4.0:
            band_squashed = True
            mid = (y_lo + y_hi) / 2
            y_hi, y_lo = mid - 2.0, mid + 2.0
        svg.band(FIG_PAD, FIG_W - FIG_PAD, y_hi, y_lo)
        edge = []
        if lo is not None:
            edge.append((lo, y_lo))
        if hi is not None:
            edge.append((hi, y_hi))
        # de-collide the two boundary labels; when they cannot both fit, keep the
        # bound the data is actually near and put the full range in the note
        if len(edge) == 2 and abs(edge[0][1] - edge[1][1]) < 9.0:
            near = max(edge, key=lambda e: sum(1 for p in pts if abs(p["v"] - e[0]) < abs(p["v"] - edge[0][0])))
            edge = [near] if band_squashed else [edge[0], (edge[1][0], edge[1][1] - 9.0)]
        for val, yy in edge:
            svg.line(FIG_PAD, yy, FIG_W - FIG_PAD, yy, stroke=LADDER[3], width=0.6, dash="3 3")
            svg.text(FIG_W - FIG_PAD + 2, yy + 3, _num(val), size=FS_AXIS, fill=MUTED)
    svg.rail(FIG_PAD, FIG_W - FIG_PAD, h - 20.0, ticks=[tax.x(p["o"]) for p in pts])

    # split the polyline wherever the method changes: connecting across a method
    # change would assert comparability we do not have
    segs, cur = [], [pts[0]]
    for a, b in zip(pts, pts[1:]):
        if (a.get("method") or None) != (b.get("method") or None):
            segs.append(cur)
            cur = [b]
        else:
            cur.append(b)
    segs.append(cur)
    # A long silence must not be drawn as a solid line. A 1.4-year gap rendered
    # as a straight segment reads as "it declined steadily through here", when in
    # fact nothing is known about that stretch — same class of error as joining
    # across a method change. Draw those spans dashed and name them in the note.
    ords_all = [p["o"] for p in pts]
    steps = [b - a for a, b in zip(ords_all, ords_all[1:])]
    med = sorted(steps)[len(steps) // 2] if steps else 0
    gap_min = max(120, med * 3) if med else 120
    for seg in segs:
        for a, b in zip(seg, seg[1:]):
            wide = (b["o"] - a["o"]) >= gap_min
            svg.polyline([(tax.x(a["o"]), vax.y(a["v"])), (tax.x(b["o"]), vax.y(b["v"]))],
                         stroke=PRIMARY_HI, width=1.8,
                         dash="5 4" if wide else None)
            if wide:
                gaps_drawn.append(b["o"] - a["o"])
    for a, b in zip(segs, segs[1:]):
        svg.line(tax.x(a[-1]["o"]), vax.y(a[-1]["v"]),
                 tax.x(b[0]["o"]), vax.y(b[0]["v"]),
                 stroke=LADDER[3], width=1.0, dash="2 3")

    # data points, coloured by range status (amber outline = out of range)
    label_x = [tax.x(p["o"]) for p in pts]
    placer = LabelPlacer()
    placer.reserve(0, h - 22, FIG_W, h)          # keep labels off the date axis
    for _v, _y in (edge if ref else []):
        # only the band's own tick label, not the whole right-hand column —
        # reserving the column silently swallowed the last point's value
        placer.reserve(FIG_W - FIG_PAD, _y - 5, FIG_W, _y + 5)
    for p, lx in zip(pts, label_x):
        st = range_status(p["v"], ref)
        stroke, fill = point_colour(st, p["critical"])
        y = vax.y(p["v"])
        if p.get("censor"):
            # censored reading: hollow square + a whisker pointing the way the
            # true value lies, so a bound never reads as a measurement
            svg.rect(lx - 2.6, y - 2.6, 5.2, 5.2, fill=CARD, stroke=stroke, width=1.4)
            dy = 5.0 if p["censor"] == "left" else -5.0
            svg.line(lx, y + (2.6 if dy > 0 else -2.6), lx, y + dy,
                     stroke=stroke, width=1.2)
            svg.raw(f'<title>{esc(str(p["raw"]) + _u(unit))} @ {esc(p["t"])}'
                    f'（超出检测限，按限值绘制）</title>')
        else:
            svg.circle(lx, y, 2.8, fill=(CARD if fill == "none" else fill),
                       stroke=stroke, width=1.6,
                       title=f'{p["raw"]}{_u(unit)} @ {p["t"]}')
        ly = placer.place(lx, y, p["raw"], FS_VALUE, gap=6.0)
        if ly is None:
            # No clear slot: drop the label rather than print it on top of a
            # neighbour. The value stays reachable in the point's <title>, and
            # the reading note reports how many were dropped — an unreadable
            # smear of digits is worse than an honest omission.
            dropped.append(p)
        else:
            svg.text(lx, ly, f'{p["raw"]}', size=FS_VALUE, fill=INK,
                     anchor="middle", weight=700)
    # Date labels get their own pass. Two follow-ups a fortnight apart inside a
    # 1.8-year span land on the same pixel and print as "20226-06-07"; the axis
    # only needs enough dates to orient the reader, so drop the ones that would
    # collide — but never the last, which anchors "how recent is this?".
    MIN_DATE_GAP = 34.0
    keep, last_x = [], None
    for p, lx in zip(pts, label_x):
        if last_x is None or lx - last_x >= MIN_DATE_GAP:
            keep.append((p, lx))
            last_x = lx
    if keep and keep[-1][0] is not pts[-1]:
        if label_x[-1] - keep[-1][1] < MIN_DATE_GAP:
            keep.pop()
        keep.append((pts[-1], label_x[-1]))
    for p, lx in keep:
        svg.text(lx, h - 9, _date_label(p["t"]), size=FS_AXIS, fill=MUTED, anchor="middle")

    note, caveats = reading_note(pts, unit, ref, spec.get("reference_source"))
    if gaps_drawn:
        longest = max(gaps_drawn)
        caveats.append(f"图中虚线段表示这期间档案里没有该指标的记录（最长一段约 "
                       f"{_humanise_days(longest)}），线只是把两端的点连起来，"
                       f"不代表这段时间的真实变化。")
    if dropped:
        caveats.append(f"有 {len(dropped)} 个点的数值因为时间靠得太近，标在图上会互相压住，"
                       f"已省略数字标签（点仍在图上，把鼠标停在点上可看到具体数值）。"
                       f"完整数值见下方或原报告。")
    if band_squashed:
        lo, hi = ref
        rng = (f"{_num(lo)}–{_num(hi)}" if lo is not None and hi is not None
               else (f"≤{_num(hi)}" if hi is not None else f"≥{_num(lo)}"))
        caveats.append(f"图中数值远离参考区间（{rng}{_u(unit)}），区间带已按最小高度显示，"
                       f"不代表其真实宽度。")
    legend = ["● 参考区间内", "○ 参考区间外（琥珀描边）"] if ref else []
    if any(p["critical"] for p in pts):
        legend.append("● 源报告标注危急值")
    return svg, note, legend, caveats, f"{metric}{_u(unit)}"


# ── C3 · treatment swimlane ──────────────────────────────────────────────────
def recipe_swimlane(spec):
    eps = [e for e in (spec.get("episodes") or []) if isinstance(e, dict)]
    if not eps:
        raise Eligibility("没有可绘制的治疗阶段记录。")
    rows_data = []
    for e in eps:
        o1, o2 = to_ordinal(e.get("start")), to_ordinal(e.get("end"))
        if o1 is None:
            continue
        rows_data.append({"o1": o1, "o2": o2, "label": e.get("label") or e.get("regimen") or "",
                          "intent": e.get("intent") or "", "open": o2 is None,
                          "start": e.get("start"), "end": e.get("end")})
    if not rows_data:
        raise Eligibility("治疗阶段缺少可解析的开始日期。")
    rows_data.sort(key=lambda r: r["o1"])
    all_o = [r["o1"] for r in rows_data] + [r["o2"] for r in rows_data if r["o2"] is not None]
    lane_h, top = 20.0, 26.0
    h = top + lane_h * len(rows_data) + 26.0
    tax = TimeAxis(all_o, FIG_W, 96.0)  # wide left pad for the regimen names
    svg = Svg(FIG_W, h, label="治疗阶段时间轴")

    for i, r in enumerate(rows_data):
        y = top + i * lane_h
        svg.line(6, y + lane_h / 2, FIG_W - FIG_PAD, y + lane_h / 2, stroke=RULE, width=0.5)
        shown, full = truncate(r["label"], 12)
        svg.text(6, y + lane_h / 2 + 3, shown, size=FS_BODY, fill=INK, weight=600,
                 title=full if full != shown else None)
        x1 = tax.x(r["o1"])
        x2 = tax.x(r["o2"]) if r["o2"] is not None else FIG_W - FIG_PAD
        shade = LADDER[min(4, 1 + i % 3)]
        svg.rect(x1, y + 4, max(2.0, x2 - x1), lane_h - 10, fill=shade, rx=2.0)
        if r["open"]:
            # open-ended episode: dashed tail, never a hard edge implying an end
            svg.line(x2 - 12, y + lane_h / 2, x2 + 4, y + lane_h / 2,
                     stroke=PRIMARY, width=1.0, dash="2 2")
        # intent label always sits after the bar, in one consistent column —
        # placing it inside when it happens to fit made the three lanes read as
        # three different chart conventions
        if r["intent"]:
            svg.text(x2 + 6, y + lane_h / 2 + 3, str(r["intent"])[:6],
                     size=FS_BODY, fill=MUTED_DEEP)
    # time rail — one tick per episode boundary, labels de-collided by month
    yb = top + lane_h * len(rows_data) + 6
    tick_xs = [tax.x(o) for o in sorted(set(all_o))]
    svg.rail(96.0, FIG_W - FIG_PAD, yb, ticks=tick_xs)
    import datetime as _dt
    labelled = []
    for o in sorted(set(all_o)):
        x = tax.x(o)
        lbl = _date_label(_dt.date.fromordinal(o).isoformat())
        if any(abs(x - lx) < 34.0 for lx, _ in labelled) or any(l == lbl for _, l in labelled):
            continue
        labelled.append((x, lbl))
        svg.text(x, yb + 11, lbl, size=FS_AXIS, fill=MUTED, anchor="middle")

    note = (f"{len(rows_data)} 段治疗记录，按源报告的开始与结束日期排布"
            f"{'；虚线尾表示记录中未写结束日期' if any(r['open'] for r in rows_data) else ''}。")
    caveats = ["时间对齐不表示疗效或因果。各段的划分与命名取自源病历记录。"]
    return svg, note, [], caveats, "治疗阶段"


# ── C4 · lab panel reference bars ────────────────────────────────────────────
def recipe_panel(spec):
    rows = [r for r in (spec.get("rows") or []) if isinstance(r, dict)]
    if not rows:
        raise Eligibility("没有可绘制的检验项目。")
    lane, top, lx = 17.0, 24.0, 108.0
    h = top + lane * len(rows) + 16.0
    svg = Svg(FIG_W, h, label="检验项目与参考区间对照")
    track_x1, track_x2 = lx, FIG_W - 76.0
    for i, r in enumerate(rows):
        y = top + i * lane
        name, full = truncate(r.get("analyte", ""), 13)
        svg.text(6, y + 4, name, size=FS_BODY, fill=INK, weight=600,
                 title=full if full != name else None)
        ref = parse_reference_range(r.get("reference_range"))
        v = to_float(r.get("value"))
        svg.line(track_x1, y, track_x2, y, stroke=RULE, width=0.5)
        if ref and v is not None:
            lo, hi = ref
            # normalise onto the track: the band occupies the middle 60%
            lo_e = lo if lo is not None else min(v, hi if hi is not None else v) * 0.5
            hi_e = hi if hi is not None else max(v, lo_e) * 1.5
            spanv = max(_EPS, hi_e - lo_e)
            dom_lo, dom_hi = lo_e - spanv * 0.6, hi_e + spanv * 0.6
            dom_lo, dom_hi = min(dom_lo, v), max(dom_hi, v)
            def px(val):
                return track_x1 + (val - dom_lo) / max(_EPS, dom_hi - dom_lo) * (track_x2 - track_x1)
            svg.rect(px(lo_e), y - 4.5, px(hi_e) - px(lo_e), 9, fill=BAND, rx=1.5)
            st = range_status(v, ref)
            stroke, fill = point_colour(st, bool(r.get("critical")))
            svg.circle(px(v), y, 3.0, fill=(CARD if fill == "none" else fill),
                       stroke=stroke, width=1.6,
                       title=f'{r.get("value")} {r.get("unit","")} · 参考 {r.get("reference_range","")}')
            svg.text(track_x2 + 5, y + 3.5, f'{r.get("value")}{_u(r.get("unit"))}',
                     size=FS_BODY, fill=INK, weight=700)
        else:
            # No parseable range (or a non-numeric result like 阴性/阳性): keep the
            # row visually intact — a gap in the track reads as missing data, when
            # in fact the VALUE is present and only the band is absent.
            svg.line(track_x1, y, track_x2, y, stroke=RULE, width=0.5, dash="2 3")
            svg.text(track_x1 + 4, y + 3.5, f'{r.get("value","")}{_u(r.get("unit"))}',
                     size=FS_BODY, fill=INK, weight=700)
            svg.text(track_x2 + 5, y + 3.5, "无参考区间", size=FS_BODY, fill=MUTED)
    n_ref = sum(1 for r in rows if parse_reference_range(r.get("reference_range")))
    note = (f"{len(rows)} 个检验项目，{n_ref} 项带本次报告的参考区间"
            f"（淡紫带 = 参考区间，圆点 = 本次测量值）。")
    caveats = []
    if n_ref < len(rows):
        caveats.append(f"其中 {len(rows) - n_ref} 项本次报告未提供可解析的参考区间，"
                       f"未画区间带；不同实验室与方法的区间不同，不能套用通用值。")
    return svg, note, ["淡紫带 = 参考区间", "○ 琥珀描边 = 区间外"], caveats, "检验项目"


