def _numeric_series(series):
    """Filter to plottable points [(ordinal, value, raw_value)], sorted by day."""
    pts = []
    if not isinstance(series, list):
        return pts
    for p in series:
        if not isinstance(p, dict):
            continue
        v = to_float(p.get("v"))
        o = to_ordinal(p.get("t"))
        if v is None or o is None:
            continue
        pts.append((o, v, p.get("v")))
    pts.sort(key=lambda x: x[0])
    return pts


def _x_axis(ordinals, w: float, pad: float):
    lo, hi = min(ordinals), max(ordinals)
    span = hi - lo
    inner = w - 2 * pad
    if span <= 0:
        cx = pad + inner / 2
        return lambda o: cx, lo, hi
    return lambda o: pad + (o - lo) / span * inner, lo, hi


def _y_of(v: float, vmin: float, vmax: float, h: float, pad: float) -> float:
    inner = h - 2 * pad
    if vmax - vmin < _EPS:
        return h / 2
    return h - pad - (v - vmin) / (vmax - vmin) * inner


def _direction(pts):
    """Direction of the MOST RECENT segment. Retained for backwards
    compatibility of the emitted field; the template no longer renders an arrow
    glyph from it (chart-style.md §red-restraint: a downward arrow is read as
    'improving', which is a verdict we may not give)."""
    if len(pts) < 2:
        return "single" if pts else "flat"
    prev, last = pts[-2][1], pts[-1][1]
    if abs(last - prev) < _EPS:
        return "flat"
    return "down" if last < prev else "up"


def _enrich_series(obj, w, h, pad, with_area: bool, with_dots: bool = False):
    """Inject svg_points / svg_area_d / dots / direction / point_count.

    Byte-identical to compute_sparklines._enrich_series. Do not 'improve' the
    geometry here: the 段D template is a 1:1 golden artefact and its rendered
    output is diffed in CI.
    """
    pts = _numeric_series(obj.get("series"))
    obj["point_count"] = len(pts)
    obj["direction"] = _direction(pts)
    if pts:
        obj["last_value"] = str(pts[-1][2])
        obj["first_value"] = str(pts[0][2])
    else:
        obj["last_value"] = ""
        obj["first_value"] = ""
    if not pts:
        obj["svg_points"] = ""
        if with_area:
            obj["svg_area_d"] = ""
        if with_dots:
            obj["dots"] = []
        return []
    xf, _, _ = _x_axis([o for o, _, _ in pts], w, pad)
    vmin = min(v for _, v, _ in pts)
    vmax = max(v for _, v, _ in pts)
    coords = [(xf(o), _y_of(v, vmin, vmax, h, pad)) for o, v, _ in pts]
    obj["svg_points"] = " ".join(f"{fmt(x)},{fmt(y)}" for x, y in coords) if len(coords) >= 2 else ""
    if with_area:
        if len(coords) >= 2:
            base = h - pad
            d = ["M", f"{fmt(coords[0][0])},{fmt(coords[0][1])}"]
            for x, y in coords[1:]:
                d += ["L", f"{fmt(x)},{fmt(y)}"]
            d += ["L", f"{fmt(coords[-1][0])},{fmt(base)}",
                  "L", f"{fmt(coords[0][0])},{fmt(base)}", "Z"]
            obj["svg_area_d"] = " ".join(d)
        else:
            obj["svg_area_d"] = ""
    if with_dots:
        obj["dots"] = [{"cx": fmt(x), "cy": fmt(y)} for x, y in coords]
    return [raw for _, _, raw in pts]


def _enrich_markers(hero, w, pad):
    """Place treatment-line markers on the hero series' time axis."""
    markers = hero.get("treatment_markers")
    if not isinstance(markers, list) or not markers:
        return
    dict_markers = [m for m in markers if isinstance(m, dict)]
    pts = _numeric_series(hero.get("series"))
    if not pts:
        for i, m in enumerate(dict_markers):
            m["idx"] = i + 1
            t = m.get("t")
            m["marker_date"] = t[:7] if isinstance(t, str) and len(t) >= 7 else (t or "")
            m["marker_x"] = fmt(pad)
            m["marker_x_left"] = fmt(pad - 6)
            m["badge_pct"] = fmt(pad / w * 100)
            m["badge_cy"] = fmt(BADGE_CY0)
            m["badge_ty"] = fmt(BADGE_CY0 + 3.3)
        return
    ordinals = [o for o, _, _ in pts]
    xf, lo, hi = _x_axis(ordinals, w, pad)
    for i, m in enumerate(dict_markers):
        m["idx"] = i + 1
        t = m.get("t")
        m["marker_date"] = t[:7] if isinstance(t, str) and len(t) >= 7 else (t or "")
        o = to_ordinal(t)
        x = pad if o is None else xf(max(lo, min(hi, o)))
        m["_x"] = x
        m["marker_x"] = fmt(x)
        m["marker_x_left"] = fmt(x - 6)
        m["badge_pct"] = fmt(x / w * 100)
    row_last_x = []
    for m in sorted(dict_markers, key=lambda mm: mm["_x"]):
        x = m["_x"]
        row = next((r for r, lx in enumerate(row_last_x) if x - lx >= BADGE_GAP), None)
        if row is None:
            row = len(row_last_x)
            row_last_x.append(x)
        else:
            row_last_x[row] = x
        cy = BADGE_CY0 + row * BADGE_DY
        m["badge_cy"] = fmt(cy)
        m["badge_ty"] = fmt(cy + 3.3)
        del m["_x"]


def _enrich_reference_band(chart):
    """ADDITIVE: reference-range band geometry for the hero chart (C1).

    Emitted as band_y / band_h in the SAME viewBox as svg_points, so the
    template can draw <rect> under the curve. Absent (empty string) when the
    range is missing or unparseable — the template then shows the explicit
    'no parseable reference range' note rather than silently omitting the band,
    because a missing band and a band you happen to sit inside look identical
    otherwise.
    """
    pts = _numeric_series(chart.get("series"))
    raw_ref = chart.get("reference_range")
    ref = parse_reference_range(raw_ref)
    chart["reference_range_text"] = str(raw_ref) if raw_ref else ""
    if not pts or not ref:
        chart["band_y"] = ""
        chart["band_h"] = ""
        chart["has_band"] = ""
        return
    vmin = min(v for _, v, _ in pts)
    vmax = max(v for _, v, _ in pts)
    lo, hi = ref
    # expand the domain so the band is visible even when every point sits inside
    if lo is not None:
        vmin, vmax = min(vmin, lo), max(vmax, lo)
    if hi is not None:
        vmin, vmax = min(vmin, hi), max(vmax, hi)
    y_lo = _y_of(lo, vmin, vmax, HERO_H, HERO_PAD) if lo is not None else HERO_H - HERO_PAD
    y_hi = _y_of(hi, vmin, vmax, HERO_H, HERO_PAD) if hi is not None else HERO_PAD
    top, bottom = min(y_lo, y_hi), max(y_lo, y_hi)
    chart["band_y"] = fmt(top)
    chart["band_h"] = fmt(max(0.0, bottom - top))
    chart["has_band"] = "1"
    # geometry moved: re-derive the curve against the EXPANDED domain so points
    # and band share one scale (otherwise a point could sit visually inside a
    # band it is numerically outside — the most dangerous possible artefact).
    xf, _, _ = _x_axis([o for o, _, _ in pts], HERO_W, HERO_PAD)
    coords = [(xf(o), _y_of(v, vmin, vmax, HERO_H, HERO_PAD)) for o, v, _ in pts]
    chart["svg_points"] = " ".join(f"{fmt(x)},{fmt(y)}" for x, y in coords) if len(coords) >= 2 else ""
    if len(coords) >= 2:
        base = HERO_H - HERO_PAD
        d = ["M", f"{fmt(coords[0][0])},{fmt(coords[0][1])}"]
        for x, y in coords[1:]:
            d += ["L", f"{fmt(x)},{fmt(y)}"]
        d += ["L", f"{fmt(coords[-1][0])},{fmt(base)}",
              "L", f"{fmt(coords[0][0])},{fmt(base)}", "Z"]
        chart["svg_area_d"] = " ".join(d)
    else:
        chart["svg_area_d"] = ""
    chart["dots"] = [{"cx": fmt(x), "cy": fmt(y)} for x, y in coords]
    # per-point status drives the marker colour (amber outline when out of range)
    statuses = [range_status(v, ref) for _, v, _ in pts]
    for dot, st in zip(chart["dots"], statuses):
        stroke, fill = point_colour(st)
        dot["stroke"] = stroke
        dot["fill"] = fill if fill != "none" else CARD


def enrich(data: dict) -> dict:
    for chart in data.get("trend_charts", []) or []:
        if isinstance(chart, dict):
            _enrich_series(chart, HERO_W, HERO_H, HERO_PAD, with_area=True, with_dots=True)
            _enrich_markers(chart, HERO_W, HERO_PAD)
            _enrich_reference_band(chart)
    for row in data.get("lab_trends", []) or []:
        if isinstance(row, dict):
            _enrich_series(row, SPARK_W, SPARK_H, SPARK_PAD, with_area=False)
    return data


# ── anti-fabrication gate (G-CHART-2) ────────────────────────────────────────
def _source_index(paths):
    idx: dict[str, set] = {}

    def add(metric, value):
        if metric is None:
            return
        key = str(metric).strip().lower()
        bucket = idx.setdefault(key, set())
        f = to_float(value)
        if f is not None:
            bucket.add(("num", round(f, 6)))
        bucket.add(("str", str(value).strip()))

    for p in paths:
        if not p:
            continue
        try:
            doc = json.loads(Path(p).read_text(encoding="utf-8"))
        except Exception:
            continue
        if not isinstance(doc, dict):
            continue
        for o in doc.get("observations", []):
            if isinstance(o, dict):
                add(o.get("metric"), o.get("value"))
        for panel in doc.get("panels", []):
            if not isinstance(panel, dict):
                continue
            analyte = panel.get("analyte")
            for v in panel.get("values", []) or []:
                if isinstance(v, dict):
                    add(analyte, v.get("value"))
        for row in doc.get("labs", []) or []:
            if isinstance(row, dict):
                name = row.get("lab_name") or row.get("name") or row.get("analyte")
                val = row.get("value") if row.get("value") is not None else row.get("lab_value")
                add(name, val)
    return idx


def _value_backed(idx, metric, raw_value) -> bool:
    if metric is None:
        return False
    bucket = idx.get(str(metric).strip().lower())
    if not bucket:
        return False
    f = to_float(raw_value)
    if f is not None and ("num", round(f, 6)) in bucket:
        return True
    return ("str", str(raw_value).strip()) in bucket


def _integrity_violations(data, idx):
    bad = []
    for chart in data.get("trend_charts", []) or []:
        if isinstance(chart, dict) and isinstance(chart.get("series"), list):
            for p in chart["series"]:
                if isinstance(p, dict) and to_float(p.get("v")) is not None:
                    if not _value_backed(idx, chart.get("metric"), p.get("v")):
                        bad.append(f"trend_charts[{chart.get('metric')!r}] value {p.get('v')!r} @ {p.get('t')!r}")
    for row in data.get("lab_trends", []) or []:
        if isinstance(row, dict) and isinstance(row.get("series"), list):
            for p in row["series"]:
                if isinstance(p, dict) and to_float(p.get("v")) is not None:
                    if not _value_backed(idx, row.get("lab_name"), p.get("v")):
                        bad.append(f"lab_trends[{row.get('lab_name')!r}] value {p.get('v')!r} @ {p.get('t')!r}")
    return bad


