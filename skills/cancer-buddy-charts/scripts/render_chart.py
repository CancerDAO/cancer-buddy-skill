# ═════════════════════════════════════════════════════════════════════════════
# G-CHART-1 — the verdict gate (floor only)
# ═════════════════════════════════════════════════════════════════════════════
# A regex list is a FLOOR, not the whole gate. It guarantees the blatant cases
# are caught; judging whether a phrasing amounts to a verdict is a semantic call
# and belongs to the skill's sub-prompt (SKILL.md §title). Never treat a pass
# here as "this caption is fine".
#
# SCOPE — this gate runs on AUTHORED text only: --title, spec-supplied captions,
# and the LLM-filled caption fields in case_summary_data.json. It deliberately
# does NOT run on:
#
#   (a) disclaimers and reading notes generated by the deterministic code below.
#       Two failures forced this. A blanket regex flags the very disclaimer
#       G-CHART-5 REQUIRES ("时间对齐不表示疗效或因果") because it cannot read
#       negation — the sentence denies the verdict it is matched on.
#   (b) clinical strings transcribed from the record. "缓解" inside 诱导缓解方案
#       is a standard regimen name, not a verdict; flagging it would reject a
#       faithfully transcribed chart label and push the pipeline toward quietly
#       renaming what the record says, which is worse than the risk it prevents.
#
# The threat model is "a model wrote a verdict into a caption", not "a fixed
# sentence we already reviewed contains a word". Deterministic output is
# governed by code review; only authored text needs a runtime gate.
VERDICT_PATTERNS = [
    r"有效", r"无效", r"起效", r"见效", r"疗效", r"响应", r"反应良好", r"应答",
    r"进展", r"缓解", r"恶化", r"好转", r"改善", r"变差", r"加重", r"减轻",
    r"复发", r"转移风险", r"控制良好", r"控制不佳", r"稳定期", r"敏感", r"耐药",
    r"预后", r"生存(?:期|率)", r"危险", r"乐观", r"不容乐观", r"严重",
    r"\b(?:CR|PR|SD|PD)\b", r"complete response", r"partial response",
    r"stable disease", r"progressive disease", r"responding", r"remission",
    r"improv(?:ing|ed|ement)", r"worsen(?:ing|ed)", r"deteriorat",
    r"效果(?:好|不好|明显|显著)", r"说明", r"提示", r"意味着", r"表明",
]
_VERDICT_RE = re.compile("|".join(VERDICT_PATTERNS), re.I)


def verdict_violations(*texts):
    """Return [(text, matched_phrase)] for any string carrying a verdict."""
    bad = []
    for t in texts:
        if not t:
            continue
        for m in _VERDICT_RE.finditer(str(t)):
            bad.append((str(t), m.group(0)))
    return bad


# ═════════════════════════════════════════════════════════════════════════════
# Reading notes — the third way between "verdict" and "number readback"
# ═════════════════════════════════════════════════════════════════════════════
# A compliant caption is not automatically a useful one. "CEA: 12.4 → 8.1" just
# reprints what the chart already shows, in the most expensive line on the card.
# A reading note instead answers "how should I read this chart, and can I trust
# it?" — comparability breaks, gaps, what the band is. That is information the
# patient cannot see for themselves but which decides whether the chart means
# anything, and it is what turns the chart into something worth handing to a
# clinician. Every sentence below is a statement about the DATA, never about the
# disease.
def reading_note(points, unit=None, ref=None, ref_source=None):
    """Compose a reading note from data facts only. Returns (note, caveats)."""
    bits, caveats = [], []
    n = len(points)
    if n == 0:
        return "没有可绘制的数据点。", []
    span_txt = ""
    ords_ = [p["o"] for p in points if p.get("o") is not None]
    if len(ords_) >= 2:
        days = max(ords_) - min(ords_)
        span_txt = f"，跨度约 {_humanise_days(days)}"
    bits.append(f"{n} 次记录{span_txt}")

    # comparability: method changes split the series' meaning
    methods = [p.get("method") for p in points if p.get("method")]
    distinct = []
    for m in methods:
        if m not in distinct:
            distinct.append(m)
    if len(distinct) > 1:
        idx = next((i + 1 for i, p in enumerate(points)
                    if p.get("method") and p.get("method") != points[0].get("method")), None)
        where = f"第 {idx} 次起" if idx else "其中"
        caveats.append(f"{where}检测方法或设备变更（{ '、'.join(str(d) for d in distinct) }），"
                       f"不同方法的绝对值不能直接比较，已分段显示。")

    # comparability: unit changes make the series meaningless if merged
    units = [p.get("unit") for p in points if p.get("unit")]
    du = []
    for u in units:
        if u not in du:
            du.append(u)
    if len(du) > 1:
        caveats.append(f"记录中出现不同单位（{'、'.join(str(u) for u in du)}），"
                       f"未做换算，请与主诊团队核对后再比较。")

    # gaps: a long silence changes how the shape should be read
    if len(ords_) >= 3:
        srt = sorted(ords_)
        gaps = [(srt[i + 1] - srt[i], i) for i in range(len(srt) - 1)]
        gmax, gi = max(gaps)
        median = sorted(g for g, _ in gaps)[len(gaps) // 2]
        if median > 0 and gmax >= max(90, median * 3):
            bits.append(f"其中有一段约 {_humanise_days(gmax)} 的空档")

    n_cens = sum(1 for p in points if p.get("censor"))
    if n_cens:
        caveats.append(f"其中 {n_cens} 个结果报告为检测限（如 <5.0），真实数值在该限值之外，"
                       f"图中按限值位置绘制并用方块标记，不代表实测值。")

    # the band, and where it came from
    if ref:
        lo, hi = ref
        if lo is not None and hi is not None:
            bits.append(f"与参考区间 {_num(lo)}–{_num(hi)}{_u(unit)} 对照")
        elif hi is not None:
            bits.append(f"与参考区间上限 {_num(hi)}{_u(unit)} 对照")
        elif lo is not None:
            bits.append(f"与参考区间下限 {_num(lo)}{_u(unit)} 对照")
        if ref_source:
            bits[-1] += f"（区间取自{ref_source}）"
    else:
        caveats.append("本次报告未提供可解析的参考区间，图中不显示区间带。"
                       "不同实验室与方法的参考区间不同，不能套用通用值。")
    return "，".join(bits) + "。", caveats


def _humanise_days(d: int) -> str:
    if d < 45:
        return f"{d} 天"
    if d < 365:
        return f"{round(d / 30.4)} 个月"
    y = d / 365.25
    return f"{y:.1f} 年".replace(".0 ", " ")


def _num(v) -> str:
    f = to_float(v)
    if f is None:
        return str(v)
    return str(int(f)) if abs(f - int(f)) < _EPS else f"{f:g}"


def _u(unit) -> str:
    return f" {unit}" if unit else ""


